#!/usr/bin/env node
// Generates Sources/Core/CityPhotos.generated.swift from the web app's
// verified Wikimedia Commons photo set (apps/web/src/lib/city-photos.ts), so
// the native backdrops and the website show the same curated photography and
// the attribution list can never drift from what we actually display.
//
// Run: node apps/ios/tools/gen-city-photos.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../..");
const src = readFileSync(resolve(repo, "apps/web/src/lib/city-photos.ts"), "utf8");

// The file is a plain `export const PHOTOS: Record<string, string[]> = {...}`.
const body = src.slice(src.indexOf("{", src.indexOf("PHOTOS")));
const photos = {};
const cityRe = /"([a-z0-9-]+)":\s*\[([\s\S]*?)\]/g;
let m;
while ((m = cityRe.exec(body))) {
  const urls = [...m[2].matchAll(/"(https:\/\/upload\.wikimedia\.org\/[^"]+)"/g)].map((u) => u[1]);
  if (urls.length) photos[m[1]] = urls;
}

const cities = Object.keys(photos).sort();
const total = cities.reduce((n, c) => n + photos[c].length, 0);

const entries = cities
  .map((slug) => {
    const list = photos[slug].map((u) => `            "${u}",`).join("\n");
    return `        "${slug}": [\n${list}\n        ],`;
  })
  .join("\n");

const swift = `// Generated by apps/ios/tools/gen-city-photos.mjs — DO NOT EDIT BY HAND.
// Source of truth: apps/web/src/lib/city-photos.ts
// ${cities.length} cities, ${total} photos.
//
// Verified Wikimedia Commons photographs of each city, at Commons' standard
// 1920px thumbnail width. Most are CC-BY / CC-BY-SA, which permit commercial
// use with attribution; attribution is satisfied by linking each photo to its
// canonical Commons file page (CC-BY-SA 4.0 §3(a)(2)), which the in-app Photo
// Credits screen does.
import Foundation

enum CityPhotos {
    static let byCity: [String: [URL]] = rawByCity.mapValues { $0.compactMap(URL.init(string:)) }

    /// Photos for a city, or an empty array when we have none verified for it.
    static func photos(for slug: String) -> [URL] { byCity[slug] ?? [] }

    /// The canonical Wikimedia Commons file page for a photo URL — the page
    /// that documents the photographer and the exact licence. This is the
    /// attribution target, so it must stay in step with how the URLs are built.
    static func commonsPage(for url: URL) -> URL? {
        let s = url.absoluteString
        // .../commons/thumb/<a>/<ab>/<File Name>.jpg/1920px-<File Name>.jpg
        guard let range = s.range(of: "/commons/thumb/") else { return nil }
        let parts = s[range.upperBound...].split(separator: "/")
        guard parts.count >= 3 else { return nil }
        let fileName = String(parts[2])
        guard let decoded = fileName.removingPercentEncoding,
              let escaped = decoded.addingPercentEncoding(withAllowedCharacters: .urlPathAllowed)
        else { return nil }
        return URL(string: "https://commons.wikimedia.org/wiki/File:\\(escaped)")
    }

    private static let rawByCity: [String: [String]] = [
${entries}
    ]
}
`;

writeFileSync(resolve(here, "../Sources/Core/CityPhotos.generated.swift"), swift);
console.log(`Wrote ${cities.length} cities / ${total} photos -> Sources/Core/CityPhotos.generated.swift`);
